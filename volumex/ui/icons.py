def _svg(name: str, color: str, stroke: float) -> bytes:
    body = _SHAPES[name]
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    ).encode()


def _dpr() -> float:
    app = QApplication.instance()
    return app.devicePixelRatio() if app else 1.0


@lru_cache(maxsize=512)
def _pixmap(name: str, color: str, size: int, stroke: float, dpr: float) -> QPixmap:
    renderer = QSvgRenderer(QByteArray(_svg(name, color, stroke)))
    px = QPixmap(round(size * dpr), round(size * dpr))
    px.fill(Qt.transparent)
    painter = QPainter(px)
    painter.setRenderHint(QPainter.Antialiasing)
    renderer.render(painter, QRectF(0, 0, px.width(), px.height()))
    painter.end()
    px.setDevicePixelRatio(dpr)
    return px


def pixmap(name: str, color: QColor | str, size: int = 18, stroke: float = 2.0) -> QPixmap:
    return _pixmap(name, QColor(color).name(QColor.HexArgb if QColor(color).alpha() < 255 else QColor.HexRgb),
                   size, stroke, _dpr())


def icon(name: str, color: QColor | str, size: int = 18, stroke: float = 2.0) -> QIcon:
    return QIcon(pixmap(name, color, size, stroke))


def paint_icon(painter: QPainter, name: str, rect: QRectF, color: QColor | str, stroke: float = 2.0) -> None:
    """Draw an icon straight into a painter (crisp at any size)."""
    renderer = QSvgRenderer(QByteArray(_svg(name, QColor(color).name(), stroke)))
    painter.save()
    if QColor(color).alpha() < 255:
        painter.setOpacity(painter.opacity() * QColor(color).alphaF())
    renderer.render(painter, rect)
    painter.restore()


_TMP = Path(tempfile.gettempdir()) / "volumex-icons"


def icon_file(name: str, color: str, size: int) -> str:
    """PNG on disk, for Qt stylesheets that need an image URL."""
    _TMP.mkdir(exist_ok=True)
    path = _TMP / f"{name}-{color.strip('#')}-{size}.png"
    if not path.exists():
        pixmap(name, color, size).save(str(path), "PNG")
    return str(path)
